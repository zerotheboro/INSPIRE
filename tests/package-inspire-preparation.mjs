// Allowlisted review artifact only. Never includes private package or runtimes.
import {createRequire} from 'node:module'
import {execFileSync} from 'node:child_process'
import {createWriteStream,existsSync,readdirSync,readFileSync,writeFileSync} from 'node:fs'
import {join,resolve,sep} from 'node:path'
import {createHash} from 'node:crypto'
import assert from 'node:assert/strict'
const require=createRequire(import.meta.url),archiver=require('archiver')
const out='docs/evidence/generative-preparation'
const manifestPath=join(out,'package-manifest.json').replaceAll('\\','/')
const target='INSPIRE-review-model-preparation-2026-11-09.zip'
const selected=new Set(),root=resolve('.')
function add(file){assert.ok(existsSync(file),'Missing review payload: '+file);selected.add(file.replaceAll('\\','/'))}
function walk(dir,predicate=()=>true){
  for(const e of readdirSync(dir,{withFileTypes:true})){
    assert.ok(!e.isSymbolicLink(),'Refuse symlink: '+e.name)
    const f=join(dir,e.name)
    if(e.isDirectory())walk(f,predicate);else if(predicate(f))add(f)
  }
}
for(const f of ['.gitignore','.firebaserc','ads.txt','eslint.config.js','firebase.json','firestore.rules','index.html',
  'package.json','package-lock.json','README.md','REVIEW.md','UNRESOLVED.md','vite.config.ts',
  'tsconfig.app.json','tsconfig.json','tsconfig.node.json','functions/.eslintrc.js','functions/.gitignore',
  'functions/package.json','functions/package-lock.json','functions/tsconfig.json','functions/tsconfig.dev.json',
  'functions/lint.cjs','functions/controller040_bridge.py','functions/inspire_generative_adapter.py'])add(f)
for(const dir of ['src','public','functions/src'])walk(dir)
walk('tests',f=>/\.(mjs|ps1|py)$/.test(f))
for(const e of readdirSync('docs'))if(e.endsWith('.md'))add('docs/'+e)
for(const dir of ['docs/evidence/scope-a040',out])walk(dir,f=>/\.(json|txt|patch|png|md)$/.test(f)&&
  !/(package-manifest|zip-audit|initial-interface|emulator-initial)/.test(f))
const current=JSON.parse(readFileSync(join(out,'executed-checks.json'),'utf8'))
for(const name of ['candidate-interface','source-candidates','backend-lint','functions-build','website-build',
  'public-build-audit','website-browser','production-browser'])assert.equal(current.results[name]?.passed,true,name)
const prior=JSON.parse(readFileSync('docs/evidence/scope-a040/executed-checks.json','utf8'))
assert.ok(Object.values(prior).every(r=>r.passed),'Previous milestone verification failure')
const forbidden=/(^|\/)(node_modules|\.git|\.tools\.local|\.private\.local|dist|lib|__pycache__)(\/|$)|(^|\/)\.env|\.(sqlite|sqlite3|db|log|har|pyc|tsbuildinfo|zip|exe|dll)$/i
const patterns=[/-----BEGIN (?:RSA |EC )?PRIVATE KEY-----[\r\n]+[A-Za-z0-9+/=]{32,}/,
  /\bsk-(?:proj-|svcacct-)?[A-Za-z0-9_-]{24,}/,/"private_key"\s*:\s*"-----BEGIN/,
  /"type"\s*:\s*"service_account"/]
const files=[...selected].sort().map(f=>{
  assert.ok(!forbidden.test(f),'Forbidden review payload: '+f)
  const data=readFileSync(f)
  if(!/\.(png|jpe?g|webp|gif|ico)$/i.test(f))for(const p of patterns)assert.ok(!p.test(data.toString('utf8')),'Potential credential: '+f)
  return {relativePath:f,bytes:data.length,sha256:createHash('sha256').update(data).digest('hex')}
})
writeFileSync(manifestPath,JSON.stringify({purpose:'Scope A engineering review; no model, clinical, source-use or deployment approval',
  archive:target,manifestSelfExcludedFromHashList:true,createdAt:new Date().toISOString(),
  exclusions:['credentials/.env','.git','node_modules','private original documents and external Controller package',
    'databases/exports','browser profiles','portable runtimes','build output/cache','real user data'],
  scan:'Executed finite path/private-key/provider-key scan. Public Firebase web configuration is source, not a server credential.',
  evidenceDomains:{previousMilestone:'docs/evidence/scope-a040',currentPreparation:out,
    arbitraryCandidates:'Offline test harness only, not generated by a model',liveAdapter:'unconditionally disabled'},files},null,2))
const archive=archiver('zip',{zlib:{level:9}}),output=createWriteStream(target,{flags:'wx'})
const done=new Promise((finish,reject)=>{output.on('close',finish);output.on('error',reject);archive.on('error',reject);archive.on('warning',reject)})
archive.pipe(output)
for(const f of [...files.map(f=>f.relativePath),manifestPath]){
  const absolute=resolve(f);assert.ok(absolute.startsWith(root+sep));archive.file(absolute,{name:f})
}
await archive.finalize();await done
// Independent archive reader verifies inventory, sizes, every hash and no extras.
const verify=String.raw`
$ErrorActionPreference='Stop'
Add-Type -AssemblyName System.IO.Compression.FileSystem
$manifestPath='docs/evidence/generative-preparation/package-manifest.json'
$manifest=Get-Content -LiteralPath $manifestPath -Raw -Encoding UTF8 | ConvertFrom-Json
$target='INSPIRE-review-model-preparation-2026-11-09.zip'
$zip=[IO.Compression.ZipFile]::OpenRead((Join-Path (Get-Location) $target))
try {
  $paths=@($manifest.files | ForEach-Object {$_.relativePath})+@($manifestPath)
  if($zip.Entries.Count -ne $paths.Count){throw 'ZIP count mismatch'}
  foreach($entry in $zip.Entries){if($entry.FullName -notin $paths){throw 'Unlisted payload'}}
  foreach($relative in $paths){
    $entry=$zip.GetEntry($relative);if(-not $entry){throw 'Missing payload'}
    $stream=$entry.Open();$sha=[Security.Cryptography.SHA256]::Create()
    try {$digest=[BitConverter]::ToString($sha.ComputeHash($stream)).Replace('-','').ToLowerInvariant()}
    finally {$sha.Dispose();$stream.Dispose()}
    if($relative -eq $manifestPath){$expected=(Get-FileHash -LiteralPath $manifestPath -Algorithm SHA256).Hash.ToLowerInvariant()}
    else {$record=$manifest.files | Where-Object {$_.relativePath -eq $relative};$expected=$record.sha256;if($entry.Length -ne $record.bytes){throw 'ZIP size mismatch'}}
    if($digest -ne $expected){throw ('ZIP hash mismatch: '+$relative)}
  }
} finally {$zip.Dispose()}
@{executed=$true;reader='.NET ZipArchive';entriesVerified=$paths.Count;allHashesMatch=$true;archive=$target;sha256=(Get-FileHash -LiteralPath $target -Algorithm SHA256).Hash.ToLowerInvariant();bytes=(Get-Item -LiteralPath $target).Length} | ConvertTo-Json -Compress
`
const audit=JSON.parse(execFileSync('powershell.exe',['-NoProfile','-Command',verify],{encoding:'utf8'}))
writeFileSync(join(out,'zip-audit.json'),JSON.stringify(audit,null,2))
console.log(JSON.stringify(audit))
